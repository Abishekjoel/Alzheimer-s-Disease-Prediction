"""
PDF report generation (Phase 21).

Every report generated by this module carries the medical disclaimer
required by the project spec, and prominently labels DEMO/placeholder
results as such — this function never lets a demo-mode prediction render
as if it were a validated clinical result. Every image embedded (patient
photo, uploaded MRI, Grad-CAM, Swin attention) is the real file for this
specific analysis — never a placeholder or stock image.

Visual design intentionally mirrors the web app's own theme (see
frontend/src/styles/tokens.css) — same indigo/green/amber/red palette —
so the PDF doesn't look like a disconnected, unstyled artifact bolted onto
a modern product.
"""

from pathlib import Path
from xml.sax.saxutils import escape as xml_escape

from django.conf import settings
from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    Image as RLImage,
    KeepTogether,
    PageBreak,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

# --- Brand palette (kept in sync with frontend/src/styles/tokens.css light theme) ---
PRIMARY = "#6d5dfc"
PRIMARY_SOFT = "#eeecff"
SUCCESS = "#16a34a"
SUCCESS_SOFT = "#e8f8ee"
WARNING = "#d97706"
WARNING_SOFT = "#fdf3e2"
DANGER = "#dc2626"
DANGER_SOFT = "#fceceb"
INK = "#171923"
INK_MUTED = "#5b6072"
INK_SUBTLE = "#8b90a3"
BORDER = "#e2e4ee"
SURFACE = "#f7f8fc"

CLASS_TONE = {"CN": (SUCCESS, SUCCESS_SOFT), "MCI": (WARNING, WARNING_SOFT), "AD": (DANGER, DANGER_SOFT)}
UNCERTAINTY_TONE = {"LOW": SUCCESS, "MEDIUM": WARNING, "HIGH": DANGER}

DISCLAIMER = (
    "This report is generated by an AI research system and is intended for research and "
    "educational purposes. It is not a clinical diagnosis and should not replace evaluation "
    "by a qualified healthcare professional. Predictions, confidence scores, and uncertainty "
    "estimates reflect the statistical behavior of a machine learning model, not a clinical "
    "assessment."
)

SEX_LABELS = {"M": "Male", "F": "Female", "U": "Unknown / not specified"}

PAGE_WIDTH, PAGE_HEIGHT = A4
MARGIN = 2 * cm
CONTENT_WIDTH = PAGE_WIDTH - 2 * MARGIN
HEADER_HEIGHT = 1.5 * cm
FOOTER_Y = 1.1 * cm


def _styles():
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="ReportTitle", fontName="Helvetica-Bold", fontSize=20, leading=24,
                               textColor=colors.HexColor(INK), spaceAfter=4))
    styles.add(ParagraphStyle(name="ReportSubtitle", fontName="Helvetica", fontSize=10.5, leading=14,
                               textColor=colors.HexColor(INK_MUTED), spaceAfter=14))
    styles.add(ParagraphStyle(name="PageTitle", fontName="Helvetica-Bold", fontSize=15, leading=18,
                               textColor=colors.HexColor(INK), spaceAfter=2))
    styles.add(ParagraphStyle(name="SectionHeading", fontName="Helvetica-Bold", fontSize=11.5, leading=14,
                               textColor=colors.HexColor(INK)))
    styles.add(ParagraphStyle(name="Body", fontName="Helvetica", fontSize=10, leading=14,
                               textColor=colors.HexColor(INK)))
    styles.add(ParagraphStyle(name="Caption", fontName="Helvetica", fontSize=8.5, leading=11,
                               textColor=colors.HexColor(INK_SUBTLE)))
    styles.add(ParagraphStyle(name="CaptionCenter", parent=styles["Caption"], alignment=TA_CENTER))
    styles.add(ParagraphStyle(name="CardLabel", fontName="Helvetica-Bold", fontSize=9, leading=12,
                               textColor=colors.HexColor(INK_MUTED), alignment=TA_CENTER))
    styles.add(ParagraphStyle(name="Disclaimer", fontName="Helvetica", fontSize=8.5, leading=12,
                               textColor=colors.HexColor(INK_SUBTLE)))
    styles.add(ParagraphStyle(name="ValueBig", fontName="Helvetica-Bold", fontSize=13, leading=16,
                               textColor=colors.HexColor(INK)))
    return styles


# --- Small reusable building blocks -----------------------------------------------------

def _divider(color=BORDER, thickness=1, width=CONTENT_WIDTH, space_before=2, space_after=10):
    t = Table([[""]], colWidths=[width], rowHeights=[thickness])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(color))]))
    return KeepTogether([Spacer(1, space_before), t, Spacer(1, space_after)])


def _section_heading(text, styles):
    """A short colored accent bar + bold heading, used to open every section
    so the report reads as a sequence of clearly separated cards rather than
    an unstructured wall of paragraphs."""
    bar = Table([[""]], colWidths=[0.22 * cm], rowHeights=[0.5 * cm])
    bar.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(PRIMARY))]))
    row = Table([[bar, Paragraph(text, styles["SectionHeading"])]],
                colWidths=[0.4 * cm, CONTENT_WIDTH - 0.4 * cm])
    row.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (0, 0), 0),
        ("LEFTPADDING", (1, 0), (1, 0), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return KeepTogether([row, Spacer(1, 8)])


def _callout(text, styles, tone="info"):
    """A bordered, tinted box for warnings/disclaimers — replaces plain
    colored text with an actual visually-distinct card."""
    accent, soft = {
        "info": (PRIMARY, PRIMARY_SOFT),
        "danger": (DANGER, DANGER_SOFT),
        "muted": (INK_SUBTLE, SURFACE),
    }[tone]
    style = ParagraphStyle(name="CalloutText", parent=styles["Body"], textColor=colors.HexColor(INK))
    t = Table([[Paragraph(text, style)]], colWidths=[CONTENT_WIDTH])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(soft)),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor(accent)),
        ("LINEBEFORE", (0, 0), (0, -1), 3, colors.HexColor(accent)),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12),
    ]))
    return t


def _kv_table(rows, label_width=5 * cm, total_width=CONTENT_WIDTH):
    """A bordered key/value table — every info table in the report shares
    this look (gridlines, shaded key column, consistent padding) instead of
    each one being styled ad hoc. `total_width` lets a caller fit this
    table into a narrower slot (e.g. next to a photo card) — a nested
    Table keeps its own explicit column widths regardless of its parent
    cell's size, so this must be sized correctly up front rather than
    assumed to shrink automatically."""
    data = [[Paragraph(f"<b>{xml_escape(str(k))}</b>", ParagraphStyle(name="k", fontName="Helvetica-Bold", fontSize=9.5,
                                                       textColor=colors.HexColor(INK_MUTED), leading=13)),
             Paragraph(xml_escape(str(v)), ParagraphStyle(name="v", fontName="Helvetica", fontSize=9.5,
                                               textColor=colors.HexColor(INK), leading=13))]
            for k, v in rows]
    table = Table(data, colWidths=[label_width, total_width - label_width])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor(SURFACE)),
        ("GRID", (0, 0), (-1, -1), 0.75, colors.HexColor(BORDER)),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    return table


def _fitted_image(path_str, max_width, max_height):
    """Scales an image to fit inside a fixed box while preserving aspect
    ratio, or returns None if the file is missing. Centered in its cell by
    the caller's table style, never stretched/distorted."""
    from PIL import Image as PILImage

    full_path = Path(path_str)
    if not full_path.exists():
        return None
    with PILImage.open(full_path) as im:
        w, h = im.size
    scale = min(max_width / w, max_height / h)
    img = RLImage(str(full_path), width=w * scale, height=h * scale)
    img.hAlign = "CENTER"
    return img


def _image_card(path_str, label, caption, box_size, styles):
    """One bordered, captioned image tile of a FIXED footprint (box_size).
    Used both standalone and inside a multi-column grid so that images of
    different native resolutions/aspect ratios still line up identically —
    this is what fixes 'different sizes, no alignment, no border'."""
    inner = box_size - 0.6 * cm
    img = _fitted_image(path_str, inner, inner)
    cell_content = [Paragraph(label, styles["CardLabel"]), Spacer(1, 6)]
    if img:
        cell_content.append(img)
    else:
        cell_content.append(Paragraph("Image unavailable", styles["CaptionCenter"]))
    cell_content.append(Spacer(1, 6))
    cell_content.append(Paragraph(caption, styles["CaptionCenter"]))

    # No explicit rowHeights: letting it size to content means a longer
    # 2-line caption doesn't get clipped, and cards sharing a Table row in
    # _image_grid still end up equal-height (the row grows to fit the
    # tallest cell) without needing to guess captions' rendered height.
    card = Table([[cell_content]], colWidths=[box_size])
    card.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor(BORDER)),
        ("BACKGROUND", (0, 0), (-1, -1), colors.white),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    return card


def _image_grid(cards, gap=0.4 * cm):
    """Lays out a list of equal-sized image cards in a single aligned row
    with even gaps, wrapping only if the row would overflow the page."""
    if not cards:
        return None
    row = []
    widths = []
    for i, card in enumerate(cards):
        if i > 0:
            row.append("")
            widths.append(gap)
        row.append(card)
        widths.append(card._colWidths[0] if card._colWidths else None)
    grid = Table([row], colWidths=widths)
    grid.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
    ]))
    return grid


def _probability_table(analysis, styles):
    """Each class gets a color swatch, a proportional horizontal bar, and
    its percentage — a real visualization instead of a bare number table.
    The predicted class row is tinted to match its tone."""
    # Nested Tables (the bar, the swatch+label pair) keep whatever fixed
    # width they're built with — unlike a Paragraph, they do NOT shrink to
    # fit their parent cell — so every nested table below is sized to the
    # column's width MINUS this row's own left+right padding, or it
    # overflows its cell and crowds/overlaps the next column.
    h_pad = 8
    label_col, bar_col = 6.2 * cm, 6.0 * cm
    pct_col = CONTENT_WIDTH - label_col - bar_col
    usable_label = label_col - 2 * h_pad
    usable_bar = bar_col - 2 * h_pad

    rows_data = [
        ("CN", "Cognitively Normal", analysis.prob_cn),
        ("MCI", "Mild Cognitive Impairment", analysis.prob_mci),
        ("AD", "Alzheimer's Disease", analysis.prob_ad),
    ]

    header = [
        Paragraph("Class", ParagraphStyle(name="ph", fontName="Helvetica-Bold", fontSize=9,
                                           textColor=colors.white)),
        Paragraph("Probability", ParagraphStyle(name="ph2", fontName="Helvetica-Bold", fontSize=9,
                                                  textColor=colors.white)),
        Paragraph("", styles["Body"]),
    ]
    data = [header]
    row_styles = []
    for i, (code, label, prob) in enumerate(rows_data, start=1):
        accent, soft = CLASS_TONE[code]
        pct = prob if prob is not None else 0.0
        filled = max(pct, 0.01) * usable_bar
        empty = usable_bar - filled
        bar = Table([["", ""]], colWidths=[filled, empty], rowHeights=[0.38 * cm])
        bar.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (0, 0), colors.HexColor(accent)),
            ("BACKGROUND", (1, 0), (1, 0), colors.HexColor(SURFACE)),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor(BORDER)),
            ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
            ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ]))
        swatch_w = 0.35 * cm
        swatch = Table([[""]], colWidths=[swatch_w], rowHeights=[0.3 * cm])
        swatch.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(accent))]))
        label_cell = Table([[swatch, Paragraph(f"<b>{code}</b> — {label}", styles["Body"])]],
                            colWidths=[swatch_w + 6, usable_label - swatch_w - 6])
        label_cell.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ]))
        pct_text = Paragraph(f"<b>{pct:.1%}</b>" if prob is not None else "N/A",
                              ParagraphStyle(name="pct", fontName="Helvetica-Bold", fontSize=9.5,
                                             textColor=colors.HexColor(accent)))
        data.append([label_cell, bar, pct_text])
        if code == analysis.predicted_class:
            row_styles.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor(soft)))

    table = Table(data, colWidths=[label_col, bar_col, pct_col])
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(PRIMARY)),
        ("GRID", (0, 0), (-1, -1), 0.75, colors.HexColor(BORDER)),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), h_pad),
        ("RIGHTPADDING", (0, 0), (-1, -1), h_pad),
    ] + row_styles
    table.setStyle(TableStyle(style))
    return table


def _metric_table(rows):
    data = [["Metric", "Value"]] + rows
    table = Table(data, colWidths=[CONTENT_WIDTH - 5 * cm, 5 * cm])
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(PRIMARY)),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("GRID", (0, 0), (-1, -1), 0.75, colors.HexColor(BORDER)),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor(SURFACE)))
    table.setStyle(TableStyle(style))
    return table


def _header_footer(canvas, doc, case_id, is_demo):
    """Draws the branded top bar and footer (page number, disclaimer
    strip, DEMO watermark tag) on every page via ReportLab's page
    callback — this is what gives the PDF a consistent frame instead of
    each page being a bare stack of flowables."""
    canvas.saveState()

    canvas.setFillColor(colors.HexColor(PRIMARY))
    canvas.rect(0, PAGE_HEIGHT - HEADER_HEIGHT, PAGE_WIDTH, HEADER_HEIGHT, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 12)
    canvas.drawString(MARGIN, PAGE_HEIGHT - HEADER_HEIGHT + 0.45 * cm, "NeuroVista")
    canvas.setFont("Helvetica", 8.5)
    canvas.drawString(MARGIN + 2.6 * cm, PAGE_HEIGHT - HEADER_HEIGHT + 0.48 * cm, "AI Research Report")
    canvas.setFont("Helvetica", 9)
    canvas.drawRightString(PAGE_WIDTH - MARGIN, PAGE_HEIGHT - HEADER_HEIGHT + 0.45 * cm, f"Case {case_id}")

    if is_demo:
        canvas.setFillColor(colors.HexColor(DANGER))
        canvas.setFont("Helvetica-Bold", 7.5)
        badge_w = 1.7 * cm
        canvas.roundRect(PAGE_WIDTH - MARGIN - badge_w, PAGE_HEIGHT - HEADER_HEIGHT - 0.55 * cm,
                          badge_w, 0.42 * cm, 3, fill=1, stroke=0)
        canvas.setFillColor(colors.white)
        canvas.drawCentredString(PAGE_WIDTH - MARGIN - badge_w / 2,
                                  PAGE_HEIGHT - HEADER_HEIGHT - 0.42 * cm, "DEMO DATA")

    canvas.setStrokeColor(colors.HexColor(BORDER))
    canvas.setLineWidth(0.75)
    canvas.line(MARGIN, FOOTER_Y + 0.35 * cm, PAGE_WIDTH - MARGIN, FOOTER_Y + 0.35 * cm)
    canvas.setFillColor(colors.HexColor(INK_SUBTLE))
    canvas.setFont("Helvetica", 7.5)
    canvas.drawString(MARGIN, FOOTER_Y, "Research and educational use only — not a substitute for professional medical diagnosis.")
    canvas.drawRightString(PAGE_WIDTH - MARGIN, FOOTER_Y, f"Page {doc.page}")

    canvas.restoreState()


def generate_report(analysis, out_path=None):
    """`analysis`: an analysis.models.MRIAnalysis instance (must be
    status=COMPLETED). Returns the absolute path to the generated PDF."""
    from functools import partial
    from reportlab.platypus import SimpleDocTemplate

    styles = _styles()
    case = analysis.case

    if out_path is None:
        reports_dir = Path(settings.MEDIA_ROOT) / "reports"
        reports_dir.mkdir(parents=True, exist_ok=True)
        out_path = reports_dir / f"analysis_{analysis.id}_report.pdf"

    doc = SimpleDocTemplate(
        str(out_path), pagesize=A4,
        topMargin=HEADER_HEIGHT + 0.9 * cm, bottomMargin=FOOTER_Y + 0.9 * cm,
        leftMargin=MARGIN, rightMargin=MARGIN,
    )
    page_cb = partial(_header_footer, case_id=case.case_id, is_demo=analysis.is_demo)
    story = []

    # ---- Page 1: title, patient/case info, MRI scan ----
    story.append(Paragraph("Alzheimer's Disease Prediction", styles["ReportTitle"]))
    story.append(Paragraph("Research Report — Hybrid CNN + Swin Transformer Analysis", styles["ReportSubtitle"]))

    if analysis.is_demo:
        story.append(_callout(
            "<b>DEMO / PLACEHOLDER RESULT</b> — this analysis was produced by a model that has not "
            "been trained on a real, validated dataset. It illustrates the pipeline only and carries "
            "no research or clinical validity.",
            styles, tone="danger",
        ))
        story.append(Spacer(1, 12))

    story.append(_kv_table([
        ["Case ID", case.case_id],
        ["Analysis ID", str(analysis.id)],
        ["Analysis date", analysis.created_at.strftime("%Y-%m-%d %H:%M UTC")],
        ["Report generated", timezone.now().strftime("%Y-%m-%d %H:%M UTC")],
    ]))
    story.append(Spacer(1, 16))

    story.append(_section_heading("Patient / Case Information", styles))
    info_rows = [
        ["Name", case.full_name or "Not specified"],
        ["Age", f"{case.age_years} years" if case.age_years is not None else "Not specified"],
        ["Gender", SEX_LABELS.get(case.sex, "Not specified")],
        ["Blood group", case.blood_group or "Not specified"],
        ["Weight", f"{case.weight_kg:.1f} kg" if case.weight_kg is not None else "Not specified"],
    ]

    if case.photo:
        photo_col_width = 3.8 * cm + 0.4 * cm
        info_table = _kv_table(info_rows, label_width=4.5 * cm, total_width=CONTENT_WIDTH - photo_col_width)
        photo_card = _image_card(case.photo.path, "Patient photo", " ", 3.8 * cm, styles)
        row = Table([[photo_card, info_table]], colWidths=[photo_col_width, CONTENT_WIDTH - photo_col_width])
        row.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ]))
        story.append(row)
    else:
        story.append(_kv_table(info_rows, label_width=4.5 * cm))
    story.append(Spacer(1, 16))

    story.append(_section_heading("MRI Scan", styles))
    quality_table = _kv_table([
        ["Quality score", f"{analysis.quality_score:.2f}" if analysis.quality_score is not None else "N/A"],
        ["Valid for analysis", "Yes" if analysis.quality_is_valid else "No"],
        ["Issues", "; ".join(analysis.quality_issues) if analysis.quality_issues else "None"],
    ], label_width=4.5 * cm, total_width=CONTENT_WIDTH - (5.4 * cm + 0.4 * cm))
    if analysis.image:
        mri_col_width = 5.4 * cm + 0.4 * cm
        mri_card = _image_card(analysis.image.path, "Uploaded scan", "Original preprocessed input slice.", 5.4 * cm, styles)
        mri_row = Table([[mri_card, quality_table]], colWidths=[mri_col_width, CONTENT_WIDTH - mri_col_width])
        mri_row.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ]))
        story.append(mri_row)
    else:
        story.append(_kv_table([
            ["Quality score", f"{analysis.quality_score:.2f}" if analysis.quality_score is not None else "N/A"],
            ["Valid for analysis", "Yes" if analysis.quality_is_valid else "No"],
            ["Issues", "; ".join(analysis.quality_issues) if analysis.quality_issues else "None"],
        ], label_width=4.5 * cm))

    # ---- Page 2: AI analysis result ----
    story.append(PageBreak())
    story.append(Paragraph("AI Analysis Result", styles["PageTitle"]))
    story.append(_divider())

    accent, soft = CLASS_TONE.get(analysis.predicted_class, (PRIMARY, PRIMARY_SOFT))
    result_row = Table([[
        Paragraph("PREDICTED CLASS", styles["CardLabel"]),
        Paragraph("CONFIDENCE", styles["CardLabel"]),
        Paragraph("UNCERTAINTY", styles["CardLabel"]),
    ], [
        Paragraph(f'<font color="{accent}"><b>{analysis.predicted_class or "N/A"}</b></font>', styles["ValueBig"]),
        Paragraph(f"{analysis.confidence:.1%}" if analysis.confidence is not None else "N/A", styles["ValueBig"]),
        Paragraph(
            f'<font color="{UNCERTAINTY_TONE.get(analysis.uncertainty_level, INK_SUBTLE)}"><b>'
            f'{analysis.uncertainty_level or "N/A"}</b></font>'
            + (f" ({analysis.uncertainty_score:.3f})" if analysis.uncertainty_score is not None else ""),
            styles["ValueBig"],
        ),
    ]], colWidths=[CONTENT_WIDTH / 3] * 3)
    result_row.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(SURFACE)),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor(BORDER)),
        ("INNERGRID", (0, 0), (-1, -1), 0.75, colors.HexColor(BORDER)),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("TOPPADDING", (0, 0), (-1, 0), 10), ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
        ("TOPPADDING", (0, 1), (-1, 1), 2), ("BOTTOMPADDING", (0, 1), (-1, 1), 14),
    ]))
    story.append(result_row)
    story.append(Spacer(1, 6))
    story.append(Paragraph(
        "Uncertainty reflects how consistent the model's own output distribution is for this input "
        "(Monte Carlo Dropout) — it is NOT the clinical probability that the patient has Alzheimer's disease.",
        styles["Caption"],
    ))
    story.append(Spacer(1, 16))

    story.append(_section_heading("Class Probabilities", styles))
    story.append(_probability_table(analysis, styles))

    # ---- Page 3: explainability ----
    story.append(PageBreak())
    story.append(Paragraph("Explainability", styles["PageTitle"]))
    story.append(_divider())
    story.append(Paragraph(
        "The visualizations below show real gradients (Grad-CAM) and real attention weights "
        "(Swin Transformer) computed for this specific prediction — neither is fabricated after "
        "the fact. Highlighted regions are not established medical biomarkers.",
        styles["Body"],
    ))
    story.append(Spacer(1, 14))

    card_box = 5.4 * cm
    cards = []
    for title, field, caption in [
        ("Original MRI", "image", "Uploaded, preprocessed input."),
        ("Grad-CAM", "gradcam_path", "CNN branch gradient-weighted activation."),
        ("Swin Attention", "attention_map_path", "Reconstructed window-attention weights."),
    ]:
        file_field = getattr(analysis, field)
        path_value = file_field.path if field == "image" else (
            str(Path(settings.MEDIA_ROOT) / file_field) if file_field else None
        )
        if path_value and Path(path_value).exists():
            cards.append(_image_card(path_value, title, caption, card_box, styles))

    grid = _image_grid(cards)
    if grid:
        story.append(grid)

    # ---- Page 4: technical summary ----
    story.append(PageBreak())
    story.append(Paragraph("Technical Summary", styles["PageTitle"]))
    story.append(_divider())

    story.append(_kv_table([
        ["Model version", str(analysis.model_version) if analysis.model_version else "N/A"],
        ["CNN architecture", analysis.model_version.cnn_architecture if analysis.model_version else "N/A"],
        ["Swin architecture", analysis.model_version.swin_architecture if analysis.model_version else "N/A"],
        ["Fusion method", analysis.model_version.fusion_method if analysis.model_version else "N/A"],
        ["Processing time", f"{analysis.processing_time_ms:.1f} ms" if analysis.processing_time_ms else "N/A"],
    ], label_width=4.5 * cm))

    if analysis.model_version and analysis.model_version.metrics:
        story.append(Spacer(1, 16))
        story.append(_section_heading("Model Evaluation Metrics", styles))
        metrics = analysis.model_version.metrics
        metric_rows = [[k, f"{v:.4f}" if isinstance(v, float) else str(v)] for k, v in metrics.items()
                       if not isinstance(v, (dict, list))]
        if metric_rows:
            story.append(_metric_table(metric_rows))

    # ---- Interpretation & disclaimer ----
    story.append(Spacer(1, 18))
    story.append(_section_heading("Interpretation & Disclaimer", styles))
    story.append(_callout(
        f"The model's output for this scan was <b>{analysis.predicted_class or 'N/A'}</b> with "
        f"{f'{analysis.confidence:.1%}' if analysis.confidence is not None else 'unknown'} confidence "
        f"and {analysis.uncertainty_level or 'unknown'} uncertainty. This is a statistical output "
        "from a machine learning model, not a medical diagnosis.<br/><br/>" + DISCLAIMER,
        styles, tone="muted",
    ))

    doc.build(story, onFirstPage=page_cb, onLaterPages=page_cb)
    return str(out_path)
